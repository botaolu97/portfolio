import type { NodeProps } from '@xyflow/react';
import { memo, useEffect, useState } from 'react';
import { EDITABLE } from '../content/api';
import { type FlowNode, useMapStore } from '../store/mapStore';
import { CODE_LANGUAGES } from '../store/schema';
import { useUiStore } from '../store/uiStore';
import { NodeChrome } from './NodeChrome';
import styles from './nodes.module.css';

// Shiki only loads in the editor; checked inline so the production build drops it.
const loadHighlighter = import.meta.env.DEV ? () => import('../editor/highlight') : null;

/** A code block with syntax highlighting. Double-click to edit (edit mode); anyone can copy. */
export const CodeNode = memo(function CodeNode({
  id,
  data,
  selected,
}: NodeProps<Extract<FlowNode, { type: 'code' }>>) {
  const editing = useUiStore((s) => EDITABLE && s.editingTextId === id);
  const setEditing = useUiStore((s) => s.setEditingText);
  const [copied, setCopied] = useState(false);

  // Keep the stored highlight in step with the code and language (editor only).
  useEffect(() => {
    if (!loadHighlighter || editing) return;
    let cancelled = false;
    const timer = setTimeout(async () => {
      const { highlightCode } = await loadHighlighter();
      const html = await highlightCode(data.code, data.language);
      const current = useMapStore.getState().nodes.find((n) => n.id === id);
      if (!cancelled && current?.type === 'code' && current.data.html !== html) {
        useMapStore.getState().updateNodeData<'code'>(id, { html });
      }
    }, 120);
    return () => {
      cancelled = true;
      clearTimeout(timer);
    };
  }, [id, data.code, data.language, editing]);

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(data.code);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      // Clipboard access denied: nothing to do.
    }
  };

  let body: React.ReactNode;
  if (editing) {
    body = (
      <textarea
        className={`${styles.codeInput} nodrag nowheel`}
        value={data.code}
        spellCheck={false}
        aria-label="Code"
        // biome-ignore lint/a11y/noAutofocus: editing starts on double-click, focus belongs here.
        autoFocus
        onChange={(e) =>
          useMapStore.getState().updateNodeData<'code'>(id, { code: e.target.value })
        }
        onBlur={() => setEditing(null)}
        onKeyDown={(e) => {
          if (e.key === 'Escape') setEditing(null);
          if (e.key === 'Tab' && !e.shiftKey) {
            e.preventDefault();
            e.currentTarget.setRangeText(
              '  ',
              e.currentTarget.selectionStart,
              e.currentTarget.selectionEnd,
              'end',
            );
            useMapStore.getState().updateNodeData<'code'>(id, { code: e.currentTarget.value });
          }
        }}
      />
    );
  } else if (data.html) {
    body = (
      <div
        className={`${styles.codeHtml} nowheel`}
        // Generated by Shiki from the code (escaped), in the editor.
        dangerouslySetInnerHTML={{ __html: data.html }}
      />
    );
  } else {
    body = (
      <div className={`${styles.codeHtml} nowheel`}>
        <pre>
          <code>{data.code}</code>
        </pre>
      </div>
    );
  }

  return (
    <div
      className={`${styles.code} ${data.lineNumbers ? styles.lineNumbers : ''} ${data.wrap ? styles.wrap : ''}`}
      onDoubleClick={EDITABLE ? () => setEditing(id) : undefined}
    >
      <NodeChrome selected={selected} minWidth={160} minHeight={80} />
      <div className={styles.codeBar}>
        <span className={styles.codeTitle}>{data.title || CODE_LANGUAGES[data.language]}</span>
        {data.title && <span className={styles.codeLang}>{CODE_LANGUAGES[data.language]}</span>}
        <button type="button" className={`${styles.codeCopy} nodrag`} onClick={copy}>
          {copied ? 'Copied' : 'Copy'}
        </button>
      </div>
      <div className={styles.codeBody}>{body}</div>
    </div>
  );
});
