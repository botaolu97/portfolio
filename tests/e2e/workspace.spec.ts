import { expect, test } from '@playwright/test'

test('create, switch, rename, reload, navigate history, and delete files', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Welcome!', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Add file' }).click()
  await page.getByRole('button', { name: 'New mood board', exact: true }).click()
  await page.getByLabel('File name').fill('Visual direction')
  await page.getByRole('button', { name: 'Create file', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Visual direction', exact: true })).toBeVisible()
  const boardUrl = page.url()
  await page.getByRole('button', { name: 'Add file' }).click()
  await page.getByRole('button', { name: 'New document', exact: true }).click()
  await page.getByLabel('File name').fill('Project story')
  await page.getByRole('button', { name: 'Create file', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Project story', exact: true })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('heading', { name: 'Visual direction', exact: true })).toBeVisible()
  await page.goForward()
  await expect(page.getByRole('heading', { name: 'Project story', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'File actions' }).click()
  await page.getByRole('button', { name: 'Rename', exact: true }).click()
  await page.getByLabel('File name').fill('A better story')
  await page.getByRole('button', { name: 'Save name', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'A better story', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'A better story', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close file' }).click()
  await expect(page.getByRole('region', { name: 'Empty workspace' })).toBeVisible()
  await page.getByRole('navigation', { name: 'Workspace files' }).getByRole('link', { name: 'A better story', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'A better story', exact: true })).toBeVisible()
  await page.goto(boardUrl)
  await expect(page.getByRole('heading', { name: 'Visual direction', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'File actions' }).click()
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Visual direction', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'File actions' }).click()
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('button', { name: 'Delete file', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Visual direction', exact: true })).toHaveCount(0)
  await expect(page.getByRole('navigation', { name: 'Workspace files' }).getByRole('link', { name: 'A better story', exact: true })).toBeVisible()
  await page.goto(boardUrl)
  await expect(page.getByRole('heading', { name: 'This file isn’t here.' })).toBeVisible()
})

test('validation keeps the form open and Escape returns focus to the trigger', async ({ page }) => {
  await page.goto('/')
  const trigger = page.getByRole('button', { name: 'Add file' })
  await trigger.click()
  await page.getByRole('button', { name: 'New document', exact: true }).click()
  await page.getByRole('button', { name: 'Create file', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Give your file a name.')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(trigger).toBeFocused()
})

test('a storage failure stays visible and does not claim success', async ({ page }) => {
  await page.addInitScript(() => {
    IDBObjectStore.prototype.add = function () { throw new DOMException('Disk full', 'QuotaExceededError') }
  })
  await page.goto('/')
  await page.getByRole('button', { name: 'Add file' }).click()
  await page.getByRole('button', { name: 'New mood board', exact: true }).click()
  await page.getByLabel('File name').fill('Unsaved board')
  await page.getByRole('button', { name: 'Create file', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Couldn’t save this change')
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByLabel('File name')).toHaveValue('Unsaved board')
  await expect(page.getByRole('navigation', { name: 'Workspace files' }).getByRole('link')).toHaveCount(0)
})

test('mobile navigation opens, selects a file, and closes', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Open navigation' }).click()
  await page.getByRole('button', { name: 'Add file' }).click()
  await page.getByRole('button', { name: 'New mood board', exact: true }).click()
  await page.getByLabel('File name').fill('Mobile board')
  await page.getByRole('button', { name: 'Create file', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Mobile board', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
